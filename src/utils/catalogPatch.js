const tvIds = new Set([40, 42, 43]);
const sizeIds = new Set([44, 45, 46, 47, 48, 49, 50, 51]);

export const applyCatalogPatch = (catalog) => {
  const patched = catalog.map((category) => ({
    ...category,
    items: category.items.map((section) => ({
      ...section,
      products: section.products
        .filter((product) => !hiddenIds.has(Number(product.id)))
        .map((original) => {
          // Seed ratings are not backed by real reviews, so none are shown.
          const product = { ...original };
          delete product.rating;
          if (nameFixes[Number(product.id)])
            product.productName = nameFixes[Number(product.id)];
          const fix = fixes[Number(product.id)];
          if (!fix) return product;
          const next = { ...product };
          delete next.oldPrice;
          delete next.discount;
          return {
            ...next,
            price: fix.price,
            weight: sizeIds.has(Number(product.id))
              ? (product.SIZE || []).map(String)
              : fix.weight,
            description: fix.description || product.description,
            brand: fix.brand || product.brand,
            ...(tvIds.has(Number(product.id)) ? { SIZE: [] } : {}),
          };
        }),
    })),
  }));
  for (const item of additions) {
    if (patched.some((c) => c.items.some((s) => s.products.some((p) => p.id === item.id)))) continue;
    const category = patched.find((c) => c.cat_name === item.category);
    if (!category) continue;
    let section = category.items.find((s) => s.cat_name === item.subcategory);
    if (!section) {
      section = { cat_name: item.subcategory, products: [] };
      category.items = [...category.items, section];
    }
    const product = { ...item };
    delete product.category;
    delete product.subcategory;
    section.products = [...section.products, product];
  }
  return patched;
};
